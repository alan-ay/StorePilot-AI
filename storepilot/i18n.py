class ValidationError(ValueError):
    """A domain error with a stable Chinese default and a localized UI rendering."""

    def __init__(self, message: str, *values: object):
        self.message = message
        self.values = values
        super().__init__(translate(message, "zh", *values))

    def render(self, language: str) -> str:
        values = [translate(v, language) if isinstance(v, str) else v for v in self.values]
        return translate(self.message, language, *values)
